  function installFoundryDetailsRequestGuard() {
    const detailsApp = window.foundryDetailsApp;
    const nativePlugin = window.plugin?.get?.();
    if (!detailsApp?.open || !nativePlugin?.GetFoundryDetails || detailsApp.__zhRequestGuardInstalled) return;

    const originalOpen = detailsApp.open.bind(detailsApp);
    const originalGetFoundryDetails = nativePlugin.GetFoundryDetails.bind(nativePlugin);
    let latestRequest = 0;

    detailsApp.open = function (...args) {
      const request = ++latestRequest;
      nativePlugin.GetFoundryDetails = function (uniqueID, callback) {
        // The native open() invokes this synchronously. The callback itself is
        // asynchronous, so retain this request number for its eventual result.
        return originalGetFoundryDetails(uniqueID, (success, data, ...callbackArgs) => {
          if (request !== latestRequest) return;
          callback(success, data, ...callbackArgs);
        });
      };
      try {
        return originalOpen(...args);
      } finally {
        nativePlugin.GetFoundryDetails = originalGetFoundryDetails;
      }
    };
    detailsApp.__zhRequestGuardInstalled = true;
  }

  function flush() {
    scheduled = false;
    translationFlushTimer = undefined;
    if (resizeActive) {
      pending.clear();
      return;
    }

    // Vue commonly adds a container and its descendants in the same render
    // pass. Translate only the outermost containers to avoid walking the same
    // subtree once per mutation.
    const roots = [...pending]
      .map((node) => node.nodeType === Node.TEXT_NODE ? node.parentElement : node)
      .filter((node) => node?.isConnected);
    pending.clear();
    const nodes = roots.filter((node, index) => !roots.some((other, otherIndex) => (
      index !== otherIndex && typeof other.contains === "function" && other.contains(node)
    )));
    for (const node of nodes) translateTree(node);
    translateTimerStatuses();
  }
  const observer = new MutationObserver((mutations) => {
    // Native window resizing causes many layout mutations. They do not contain
    // new UI content, so discard them until the resize operation has finished.
    if (resizeActive) return;
    for (const mutation of mutations) {
      const target = mutation.target.nodeType === Node.ELEMENT_NODE
        ? mutation.target
        : mutation.target.parentElement;
      if (target?.closest?.("#modalFroundryDetails")) {
        continue;
      }
      if (isMarketPanelElement(target)) {
        scheduleMarketTranslation();
        continue;
      }

      if (mutation.type === "characterData") pending.add(mutation.target.parentElement);
      for (const node of mutation.addedNodes ?? []) {
        const parent = node.nodeType === Node.ELEMENT_NODE ? node : node.parentElement;
        if (parent?.closest?.("#modalFroundryDetails")) continue;
        if (isMarketPanelElement(parent)) {
          scheduleMarketTranslation();
          continue;
        }
        pending.add(node);
      }
    }
    if (!scheduled && pending.size) {
      scheduled = true;
      // Coalesce a Vue render pass before walking translated content. Running
      // in a microtask caused many tiny full-subtree scans and repaint bursts.
      translationFlushTimer = setTimeout(flush, 50);
    }
  });

  function installResizeTranslationThrottle() {
    const beginResize = () => {
      resizeActive = true;
      document.documentElement.dataset.zhResizing = "true";
      clearTimeout(resizeIdleTimer);
      clearTimeout(translationFlushTimer);
      translationFlushTimer = undefined;
      pending.clear();
      scheduled = false;
      pauseTranslationObserver();
    };
    const finishResize = () => {
      clearTimeout(resizeIdleTimer);
      resizeIdleTimer = setTimeout(() => {
        resizeActive = false;
        delete document.documentElement.dataset.zhResizing;
        observeTranslations();
      }, 120);
    };

    // Overwolf's resize handles are ordinary DOM elements. Pause translation
    // before layout starts changing instead of waiting for the first resize event.
    const startsResize = (target) => target instanceof Element && Boolean(target.closest(".resize"));
    document.addEventListener("pointerdown", (event) => {
      if (startsResize(event.target)) beginResize();
    }, { capture: true, passive: true });
    document.addEventListener("mousedown", (event) => {
      if (startsResize(event.target)) beginResize();
    }, { capture: true, passive: true });

    // main.html calls this directly from each resize handle. Wrapping the
    // entry point catches the native Overwolf drag before it blurs the page.
    if (typeof window.dragResize === "function" && !window.dragResize.__zhResizeWrapped) {
      const originalDragResize = window.dragResize;
      const wrappedDragResize = function (...args) {
        beginResize();
        return originalDragResize.apply(this, args);
      };
      wrappedDragResize.__zhResizeWrapped = true;
      window.dragResize = wrappedDragResize;
    }

    window.addEventListener("pointerup", finishResize, { passive: true });
    window.addEventListener("mouseup", finishResize, { passive: true });
    // dragResize hands control to Overwolf and can blur this renderer while
    // the pointer is still held. Do not resume DOM work until the pointer is
    // released or the window receives a genuine resize completion event.
    window.addEventListener("blur", () => {
      if (!resizeActive) finishResize();
    }, { passive: true });
    window.addEventListener("resize", () => {
      beginResize();
      finishResize();
    }, { passive: true });
  }

