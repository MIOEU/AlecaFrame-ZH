  function translateString(value) {
    if (!value || !/[A-Za-z]/.test(value)) return value;
    const leading = value.match(/^\s*/)?.[0] ?? "";
    const trailing = value.match(/\s*$/)?.[0] ?? "";
    const core = value.slice(leading.length, value.length - trailing.length);
    if (!core || translatedValues.has(core)) return value;
    let translated = translations[core] || getDisplayOnlyItemTranslation(core);
    if (!translated) {
      for (const [pattern, replacement] of dynamicRules) {
        if (pattern.test(core)) {
          translated = core.replace(pattern, replacement);
          break;
        }
      }
    }
    if (!translated) {
      translated = translateCompoundText(core);
    }
    if (!translated) {
      const labeledLocation = core.match(/^([A-Za-z][A-Za-z .'-]+)(\s+\(.+\).*)$/);
      if (labeledLocation && translations[labeledLocation[1]]) {
        translated = translations[labeledLocation[1]] + labeledLocation[2];
      }
    }
    return translated ? leading + translated + trailing : value;
  }

  function translateCompoundText(core) {
    const relicQualityMatch = core.match(/^(Lith|Meso|Neo|Axi) ([A-Z]\d+) (Intact|Exceptional|Flawless|Radiant)$/i);
    if (relicQualityMatch) {
      const eraName = relicQualityMatch[1][0].toUpperCase() + relicQualityMatch[1].slice(1).toLowerCase();
      const qualityName = relicQualityMatch[3][0].toUpperCase() + relicQualityMatch[3].slice(1).toLowerCase();
      const era = translations[eraName] || getDisplayOnlyItemTranslation(eraName);
      const quality = translations[qualityName] || getDisplayOnlyItemTranslation(qualityName);
      return era && quality ? `${era} ${relicQualityMatch[2]} ${quality}` : null;
    }

    const relicMatch = core.match(/^(Lith|Meso|Neo|Axi) ([A-Z]\d+) Relic$/i);
    if (relicMatch) {
      const era = translations[relicMatch[1][0].toUpperCase() + relicMatch[1].slice(1).toLowerCase()];
      return era ? `${era} ${relicMatch[2]} 遗物` : null;
    }

    const relicNameMatch = core.match(/^(Lith|Meso|Neo|Axi) ([A-Z]\d+)$/i);
    if (relicNameMatch) {
      const era = translations[relicNameMatch[1][0].toUpperCase() + relicNameMatch[1].slice(1).toLowerCase()];
      return era ? `${era} ${relicNameMatch[2]}` : null;
    }

    const part = Object.keys(compoundPartTranslations).find(candidate => core.endsWith(` ${candidate}`));
    if (!part) return null;
    const itemName = core.slice(0, -(part.length + 1));
    const baseTranslation = getCompoundBaseTranslation(itemName);
    return baseTranslation ? `${baseTranslation} ${compoundPartTranslations[part]}` : null;
  }

  function getCompoundBaseTranslation(itemName) {
    const directTranslation = getDisplayOnlyItemTranslation(itemName) || translations[itemName];
    if (directTranslation) return directTranslation;

    const primeMatch = itemName.match(/^(.*) Prime$/);
    if (!primeMatch) return null;
    const baseTranslation = getDisplayOnlyItemTranslation(primeMatch[1]) || translations[primeMatch[1]];
    return baseTranslation ? `${baseTranslation} Prime` : null;
  }

