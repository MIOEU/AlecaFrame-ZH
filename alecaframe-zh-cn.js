  function getDisplayOnlyItemLabelSize(label, chineseName) {
    const computedStyle = window.getComputedStyle(label);
    const fontFamily = computedStyle.fontFamily || "sans-serif";
    const fontWeight = computedStyle.fontWeight || "normal";
    const canvas = document.createElement("canvas");
    const context = canvas.getContext("2d");
    if (!context) return 11;

    for (let size = 19; size >= 10; size -= 0.5) {
      context.font = `${fontWeight} ${size}px ${fontFamily}`;
      if (context.measureText(chineseName).width <= 257) return size;
    }
    return 10;
  }

  function translateDisplayOnlyItemName(englishName) {
    const directTranslation = getDisplayOnlyItemTranslation(englishName) || translateString(englishName);
    if (directTranslation !== englishName) return directTranslation;

    const primeMatch = englishName.match(/^(.*) Prime$/);
    if (primeMatch) {
      const baseTranslation = getDisplayOnlyItemTranslation(primeMatch[1]) || translations[primeMatch[1]];
      if (baseTranslation) return `${baseTranslation} Prime`;
    }

    const part = Object.keys(compoundPartTranslations).find(candidate => englishName.endsWith(` ${candidate}`));
    if (!part) return englishName;
    const itemName = englishName.slice(0, -(part.length + 1));
    const primeMatchWithPart = itemName.match(/^(.*) Prime$/);
    const baseName = primeMatchWithPart ? primeMatchWithPart[1] : itemName;
    const baseTranslation = getDisplayOnlyItemTranslation(baseName) || translations[baseName];
    const displayBaseName = baseTranslation || baseName;
    return `${displayBaseName}${primeMatchWithPart ? " Prime" : ""} ${compoundPartTranslations[part]}`;
  }

