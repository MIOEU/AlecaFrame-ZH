  function getEnglishInventorySearchTerm(searchTerm) {
    const normalizedSearch = searchTerm.trim().toLowerCase();
    if (!normalizedSearch || !/[\u3400-\u9fff]/.test(normalizedSearch)) return searchTerm;

    const directMatch = findExactEnglishItemName(normalizedSearch);
    if (directMatch) return directMatch;

    const compoundMatch = getEnglishCompoundItemSearchTerm(normalizedSearch);
    if (compoundMatch) return compoundMatch;

    const matchingNames = Object.entries(displayOnlyItemTranslations)
      .filter(([, chineseName]) => chineseName.toLowerCase().includes(normalizedSearch))
      .map(([englishName]) => englishName)
      .sort((left, right) => left.length - right.length);
    if (matchingNames.length === 1) return matchingNames[0];

    const sharedBaseName = matchingNames[0];
    return sharedBaseName && matchingNames.every(name => name.startsWith(sharedBaseName))
      ? sharedBaseName
      : searchTerm;
  }

