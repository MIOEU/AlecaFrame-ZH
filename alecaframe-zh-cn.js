    const getWeaponsByEnglishNames = englishNames => Promise.all(englishNames.map(englishName =>
      new Promise(resolve => originalGetRivenWeapons(englishName, (success, data) => {
        if (!success) return resolve([]);
        try {
          resolve(JSON.parse(data));
        } catch {
          resolve([]);
        }
      }))
    )).then(groups => {
      const seen = new Set();
      return groups.flat().filter(weapon => {
        const key = weapon.uniqueID || weapon.name;
        if (seen.has(key)) return false;
        seen.add(key);
        return true;
      });
    });

